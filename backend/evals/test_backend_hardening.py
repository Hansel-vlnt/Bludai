"""
Bludai Backend Hardening Verification Test Suite
Run this script to verify that P0/P1 backend failure modes are resolved.
"""

import sys
import os
import unittest
from pathlib import Path

# Add backend root to path
sys.path.insert(0, str(Path(__file__).parent.parent))

class TestBackendHardening(unittest.TestCase):

    def test_01_tool_output_truncation(self):
        """Verify that shell and file tools truncate massive payloads."""
        from bludai.tools.shell_tools import run_terminal_command
        
        # Test command generating massive text
        cmd = "python -c \"print('A' * 20000)\""
        result = run_terminal_command.invoke({"command": cmd})
        
        self.assertLess(len(result), 4000, "Shell output was not truncated below safe bounds!")
        self.assertIn("truncated", result.lower(), "Missing truncation notice in output!")

    def test_02_path_sanitizer_containment(self):
        """Verify that file tools strictly reject path traversal attempts."""
        from bludai.tools.file_tools import read_file, create_file
        
        # Traversal attempts
        res1 = read_file.invoke({"filepath": "../../etc/passwd"})
        self.assertIn("Error", res1, "Path traversal did not return an error!")
        
        res2 = create_file.invoke({"filepath": "../sibling_project/exploit.py", "content": "bad"})
        self.assertIn("Error", res2, "Path traversal create did not return an error!")

    def test_03_worker_json_regex_does_not_false_trigger(self):
        """Verify that generating valid package.json does not trigger tool retry loops."""
        import re
        
        # Valid code generated by an agent
        code_output = '{"name": "my-app", "version": "1.0.0", "dependencies": {}}'
        
        # Current naive check was: '{"name"' in code_output
        # Fixed regex check:
        tool_call_pattern = re.compile(r'^\s*\{\s*"name"\s*:\s*"[^"]+",\s*"arguments"\s*:\s*\{', re.DOTALL)
        
        self.assertIsNone(
            tool_call_pattern.search(code_output), 
            "Valid code was incorrectly classified as an unparsed tool call!"
        )

    def test_04_message_sequence_integrity(self):
        """Verify that supervisor message formatting maintains ChatML/OpenAI protocol."""
        from langchain_core.messages import AIMessage, ToolMessage, HumanMessage
        
        tool_call_id = "call_123"
        messages = [
            HumanMessage(content="Run check"),
            AIMessage(content="", tool_calls=[{"name": "read_file", "args": {"filepath": "test.txt"}, "id": tool_call_id}]),
            ToolMessage(content="File contents", tool_call_id=tool_call_id)
        ]
        
        # Ensure that no conversion leaves ToolMessage directly following a HumanMessage
        for i in range(1, len(messages)):
            if isinstance(messages[i], ToolMessage):
                prev = messages[i-1]
                self.assertTrue(
                    isinstance(prev, AIMessage) and bool(getattr(prev, "tool_calls", None)),
                    f"Protocol violation: ToolMessage at index {i} is preceded by {type(prev)} instead of an AIMessage with tool_calls!"
                )

if __name__ == "__main__":
    print("\n⚡ Running Bludai Backend Hardening Verification Suite...\n")
    unittest.main(verbosity=2)
